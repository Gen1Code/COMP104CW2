# Main runner

def run_all(data_dir="data"):
    ensure_dirs()

    rows = []
    per_repo_year_tables = {}

    for file in sorted(os.listdir(data_dir)):
        if not file.endswith(".json"):
            continue

        path = os.path.join(data_dir, file)
        with open(path, "r", encoding="utf-8") as f:
            repo_json = json.load(f)

        df_all, df_main = repo_df_from_json(repo_json)

        repo = df_all["repo"].iloc[0] if len(df_all) else repo_json.get("name", file.replace(".json", ""))

        m = {"repo": repo}

        # 1) commit types
        m.update(commit_type_metrics(df_main))

        # 2) co-evolution probabilities
        m.update(coevolution_probs(df_main))

        # 3) sequence metrics (two variants)
        m.update(sequence_rate_by_author(df_main, window_commits=3))
        m.update(sequence_rate_time_window(df_main, hours=72))

        # 4) file intro order (lightweight traceability)
        m.update(file_intro_order_metrics(df_main))

        # 5) commit size stats
        m.update(commit_size_stats(df_main))
        m.update(commit_size_by_type(df_main))

        rows.append(m)

        # optional per-year table for this repo
        per_repo_year_tables[repo] = per_year_commit_type_table(df_main)

        print(f"done: {repo} | commits(main, non-merge): {m['nonmerge_main_commits']}")

    summary = pd.DataFrame(rows).sort_values("repo")

    # Save tables
    summary.to_csv("analysis/tables/summary_tdd_evidence.csv", index=False)
    for repo, tdf in per_repo_year_tables.items():
        safe_repo = re.sub(r"[^A-Za-z0-9_.-]+", "_", repo)
        tdf.to_csv(f"analysis/tables/{safe_repo}_commit_types_per_year.csv", index=False)

    # Plots (cross-repo comparisons)
    plot_commit_type_proportions(summary, "analysis/figures/commit_type_proportions.png")
    plot_sequence_rates(
        summary,
        "sequence_rate",
        "Test-only commits followed soon by code/mixed (next 3 commits, same author)",
        "analysis/figures/sequence_rate_next3.png",
    )
    plot_sequence_rates(
        summary,
        "sequence_rate_time_window",
        "Test-only commits followed by code/mixed within 72h (same author)",
        "analysis/figures/sequence_rate_72h.png",
    )
    plot_sequence_rates(
        summary,
        "p_test_change_given_code_change",
        "P(test change | code change) by repository",
        "analysis/figures/p_test_given_code.png",
    )
    plot_intro_order(summary, "analysis/figures/file_intro_order.png")
    plot_commit_size(summary, "analysis/figures/commit_size_median_p95.png")

    print("saved:")
    print(" - analysis/tables/summary_tdd_evidence.csv")
    print(" - analysis/figures/*.png")
    print(" - analysis/tables/*_commit_types_per_year.csv")
    return summary


if __name__ == "__main__":
    # If your mined json folder has a different name, change it here.
    run_all(data_dir="data")